"""Build reports/classification.md from saved predictions: python -m aerofix.classify.report

Reads models/classify/<run>/preds_{val,test}.npz (+ history.json) and
models/classify/ablations_tfidf.csv. Nothing is retrained here. Model selection
uses VAL; test numbers are reported for the frozen models.
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from aerofix.classify.data import TARGETS, LabelSpace, load_frame
from aerofix.classify.metrics import per_class, plot_confusion, summary
from aerofix.config import load_config
from aerofix.utils import get_logger, md_table

log = get_logger(__name__)
MAIN_RUNS = {"tfidf_lr": "TF-IDF + LR", "bilstm": "BiLSTM + Word2Vec", "distilbert": "DistilBERT (multi-task)",
             "roberta": "RoBERTa-base (multi-task)"}


def load_preds(run_dir, split):
    p = run_dir / f"preds_{split}.npz"
    if not p.exists():
        return None
    z = np.load(p)
    return {"row_id": z["row_id"], **{t: z[t].astype(np.float32) for t in TARGETS}}


def main() -> None:
    cfg = load_config()
    cdir = cfg["paths"]["models"] / "classify"
    fig_dir = cfg["paths"]["reports"] / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    labels = LabelSpace.load(cdir / "labels.json")
    df = load_frame(cfg).set_index("row_id")
    train = df[df.split == "train"]
    md = ["# Classification (Phase 4)\n",
          "Generated by `python -m aerofix.classify.report`. Input: `problem_masked` (Phase 3 problem text, "
          "references masked) unless stated. Model choices use **val (2024)**; **test (2025)** is scored once "
          "with frozen models. Headline metric: macro-F1 (every class counts equally).\n"]

    # 1. Label spaces
    rows = []
    for t in TARGETS:
        for s in ("train", "val", "test"):
            y = labels.encode(t, df[df.split == s][t])
            rows.append({"target": t, "split": s, "classes": len(labels.names(t)),
                         "share_OTHER_%": round(100 * float((y == labels.names(t).index("OTHER")).mean()), 1)})
    md += ["## 1. Targets\n\nClasses are chosen from train counts. `share_OTHER` shows how much of each split "
           "falls outside the label space; a jump from train to test means the label vocabulary drifted.\n\n",
           md_table(pd.DataFrame(rows), index=False), "\n"]

    # 2. Main results
    results, available = [], {}
    for s in ("val", "test"):
        ev = df[df.split == s]
        for t in TARGETS:
            y = labels.encode(t, ev[t])
            maj = np.zeros((len(y), len(labels.names(t))), dtype=np.float32)
            maj[:, np.bincount(labels.encode(t, train[t])).argmax()] = 1
            results.append({"model": "Majority class", "split": s, "target": t, **summary(y, maj)})
    for run, nice in MAIN_RUNS.items():
        for s in ("val", "test"):
            p = load_preds(cdir / run, s)
            if p is None:
                continue
            available.setdefault(run, {})[s] = p
            ev = df.loc[p["row_id"]]
            for t in TARGETS:
                results.append({"model": nice, "split": s, "target": t, **summary(labels.encode(t, ev[t]), p[t])})
    res = pd.DataFrame(results)
    for s in ("val", "test"):
        tab = res[res.split == s].pivot_table(index="model", columns="target", values=["macro_F1", "accuracy", "top3_acc"])
        tab.columns = [f"{t}_{m}" for m, t in tab.columns]
        cols = [f"{t}_{m}" for t in TARGETS for m in ("macro_F1", "accuracy", "top3_acc")]
        tab = tab[[c for c in cols if c in tab.columns]].sort_values("ata2_macro_F1", ascending=False)
        md += [f"## 2{'a' if s == 'val' else 'b'}. Results on {s} ({'2024' if s == 'val' else '2025, frozen models'})\n\n",
               md_table(tab.rename_axis("model").round(4)), "\n"]

    val_rank = res[(res.split == "val") & (res.target == "ata2") & (res.model != "Majority class")]
    best_nice = val_rank.sort_values("macro_F1", ascending=False).model.iloc[0]
    best_run = {v: k for k, v in MAIN_RUNS.items()}[best_nice]
    md.append(f"\n**Best on val ata2 macro-F1: {best_nice}** (used for the per-class tables, confusion matrices and "
              "error analysis below, and by the app).\n")
    (cdir / "best.json").write_text(json.dumps({"best": best_run}))

    # 3. Per-class + confusion matrices for the best model on test
    p = available[best_run]["test"]
    ev = df.loc[p["row_id"]]
    for t in ("ata2", "condition"):
        y = labels.encode(t, ev[t])
        md += [f"\n## 3. {best_nice}: per-class F1 on test, {t}\n\n", md_table(per_class(y, p[t], labels.names(t)), index=False), "\n"]
        path = fig_dir / f"confusion_{t}.png"
        plot_confusion(y, p[t], labels.names(t), f"{best_nice}, test 2025, {t} (rows sum to 1)", path)
        md.append(f"\n![confusion {t}](figures/{path.name})\n")

    # 4. Ablations (TF-IDF)
    abl_path = cdir / "ablations_tfidf.csv"
    if abl_path.exists():
        abl = pd.read_csv(abl_path)
        keep = ["experiment", "eval_on", "train_rows", "macro_F1", "accuracy", "top3_acc"]
        md += ["\n## 4. Ablations with TF-IDF + LR (ata2, val)\n\nAll variants use the same fixed train sample "
               "size, so differences come from the input, not the amount of data. Character n-grams are taken "
               "from tokenised text (see 4b for why).\n\n",
               md_table(abl[keep], index=False), "\n"]
    raw_path = cdir / "ablations_tfidf_rawchar.csv"
    if raw_path.exists():
        raw = pd.read_csv(raw_path)
        raw = raw[raw.experiment.str.startswith("norm") | (raw.experiment == "leakage: problem only, masked")]
        md += ["\n### 4b. Why character n-grams use tokenised text\n\nEarlier run with character n-grams on the "
               "*raw* problem text. Normalised inputs looked +2 points better, but the 'tokenised only' control "
               "shows almost all of that gain comes from dropping punctuation before the character n-grams, not "
               "from abbreviation expansion or spelling correction. The final pipeline therefore tokenises first.\n\n",
               md_table(raw[["experiment", "macro_F1", "accuracy"]], index=False), "\n"]

    # 5. Transformer ablation runs
    extra = []
    for run, desc in (("distilbert_full_unmasked", "full report, UNMASKED"), ("distilbert_full_masked", "full report, masked"),
                      ("distilbert", "problem only, masked (main model)")):
        h = cdir / run / "history.json"
        if h.exists():
            e1 = json.loads(h.read_text())[0]
            extra.append({"DistilBERT input": desc, "val ata2 macro-F1 after 1 epoch": e1["val_ata2_macro_F1"],
                          "val ata2 accuracy after 1 epoch": e1["val_ata2_acc"]})
    if extra:
        md += ["\n## 5. Leakage ablation with DistilBERT (equal budget: 1 epoch each)\n\n",
               md_table(pd.DataFrame(extra), index=False), "\n"]
    fam_rows = []
    for fam in ("A320", "B737"):
        p = load_preds(cdir / f"distilbert_{fam}", "val")
        if p is None:
            continue
        ev = df.loc[p["row_id"]]
        for evf in ("A320", "B737"):
            m = (ev.family == evf).values
            fam_rows.append({"train on": fam, "eval on val": evf,
                             **summary(labels.encode("ata2", ev[m].ata2), p["ata2"][m])})
    if fam_rows:
        md += ["\n## 6. Cross-family transfer with DistilBERT (ata2, val; equal train size per family)\n\n",
               md_table(pd.DataFrame(fam_rows), index=False), "\n"]

    # 7. Training curves
    for run, nice in MAIN_RUNS.items():
        h = cdir / run / "history.json"
        if h.exists():
            md += [f"\n### Training history: {nice}\n\n", md_table(pd.DataFrame(json.loads(h.read_text())), index=False), "\n"]

    # 8. Error analysis
    p = available[best_run]["test"]
    ev = df.loc[p["row_id"]].assign(pred=p["ata2"].argmax(1), conf=p["ata2"].max(1))
    ev["true"] = labels.encode("ata2", ev.ata2)
    names = labels.names("ata2")
    wrong = ev[ev.pred != ev.true].sample(20, random_state=cfg["seed"])
    err = pd.DataFrame({"problem text": wrong.problem_masked.str.slice(0, 110), "true": [names[i] for i in wrong.true],
                        "predicted": [names[i] for i in wrong.pred],
                        "confidence": [f"{c:.2f}" for c in wrong.conf]})
    md += [f"\n## 8. Error sample ({best_nice}, test, ata2, 20 random mistakes)\n\n", md_table(err, index=False), "\n"]

    out = cfg["paths"]["reports"] / "classification.md"
    out.write_text("".join(md), encoding="utf-8")
    res.to_csv(cfg["paths"]["reports"] / "classification_results.csv", index=False)
    log.info("wrote %s (best: %s)", out, best_nice)


if __name__ == "__main__":
    main()
