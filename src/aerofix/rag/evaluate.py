"""Evaluate the cited LLM summaries: python -m aerofix.rag.evaluate [--n 50]

Runs the full Advisor (index = train + val) on N random test (2025) problem texts and
measures, per summary:
  citation validity   share of cited labels that exist in the context
  has citation        summary cites at least one [Case]/[doc] label
  hallucinated refs   manual references written in the summary but absent from the context
  latency             LLM seconds and end-to-end seconds (after one warm-up call)
Faithfulness needs a human: reports/rag_faithfulness_sheet.csv lists each summary
with its evidence and an empty 1-5 score column (rubric in reports/rag.md).
"""
from __future__ import annotations

import argparse

import numpy as np
import pandas as pd

from aerofix.config import load_config
from aerofix.pipeline import Advisor
from aerofix.utils import get_logger, md_table

log = get_logger(__name__)
RUBRIC = """| Score | Meaning |
|---|---|
| 5 | Every statement is supported by the cited evidence; no invented procedures or values |
| 4 | Supported, minor imprecision (e.g. rounding, slightly over-general wording) |
| 3 | Mostly supported; one claim weakly supported or cited to the wrong case |
| 2 | Several unsupported claims, or advice beyond the evidence |
| 1 | Misleading or invents procedures / references |"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=50)
    ap.add_argument("--model", help="override the Ollama model (e.g. llama3.2:3b); report gets a suffix")
    args = ap.parse_args()
    cfg = load_config()
    suffix = ""
    if args.model:
        cfg["llm"]["model"], suffix = args.model, "_" + args.model.replace(":", "_").replace(".", "")
    adv = Advisor(cfg)
    test = pd.read_parquet(cfg["paths"]["processed"] / "sdr_a320_b737.parquet",
                           columns=["row_id", "split", "family", "variant", "ata2"])
    test = test[test.split == "test"].merge(
        pd.read_parquet(cfg["paths"]["processed"] / "sdr_segments.parquet", columns=["row_id", "problem_text"]), on="row_id")
    test = test[test.problem_text.str.split().str.len() >= 4].sample(args.n, random_state=cfg["seed"])

    adv.advise("A320", "A320", "LAV SMOKE DETECTOR INOP")  # warm-up: loads the LLM into GPU memory
    rows, sheet = [], []
    for r in test.itertuples():
        out = adv.advise(r.family, r.variant, r.problem_text)
        s = out["summary"]
        rows.append({"row_id": r.row_id, "true_ata2": r.ata2, "pred_ata2": out["system"]["ata2"][0][0],
                     "n_citations": s["n_citations"], "n_invalid": len(s["invalid_citations"]),
                     "n_halluc_refs": len(s["hallucinated_refs"]), "has_citation": s["has_citation"],
                     "ok": s["ok"], "llm_s": s["seconds"], "total_s": out["timings"]["total_ms"] / 1000,
                     "non_llm_ms": out["timings"]["total_ms"] - out["timings"].get("llm_ms", 0)})
        sheet.append({"row_id": r.row_id, "fault": r.problem_text, "summary": s["summary"],
                      "evidence": out["evidence"].render(), "faithfulness_1_to_5": ""})
        log.info("%d/%d ok=%s llm=%.1fs", len(rows), args.n, s["ok"], s["seconds"])
    res = pd.DataFrame(rows)
    total_cit = res.n_citations.sum()
    summary = pd.DataFrame([{
        "queries": len(res),
        "citation validity": f"{1 - res.n_invalid.sum() / max(total_cit, 1):.1%}",
        "summaries with >= 1 citation": f"{res.has_citation.mean():.1%}",
        "summaries with a hallucinated reference": f"{(res.n_halluc_refs > 0).mean():.1%}",
        "fully valid summaries": f"{res.ok.mean():.1%}",
        "mean citations / summary": round(res.n_citations.mean(), 1),
        "LLM s (median / p90)": f"{res.llm_s.median():.1f} / {res.llm_s.quantile(0.9):.1f}",
        "end-to-end s (median / p90)": f"{res.total_s.median():.1f} / {res.total_s.quantile(0.9):.1f}",
        "non-LLM ms (median)": round(res.non_llm_ms.median()),
    }]).T.rename(columns={0: "value"}).rename_axis("metric")
    rep = cfg["paths"]["reports"]
    pd.DataFrame(sheet).to_csv(rep / f"rag_faithfulness_sheet{suffix}.csv", index=False)
    res.to_csv(rep / f"rag_results{suffix}.csv", index=False)
    ex = [f"### Example {i + 1}\n\n**Fault:** {sheet[i]['fault']}\n\n**Summary:** {sheet[i]['summary']}\n\n"
          for i in range(min(4, len(sheet)))]
    bad = res[~res.ok]
    md = ["# RAG + LLM summary (Phase 7)\n\n",
          f"Generated by `python -m aerofix.rag.evaluate`. {len(res)} random 2025 test faults through the full "
          f"pipeline (index: train + val reports; {cfg['llm']['model']} via Ollama, temperature 0.2). "
          "Passages: AMT Handbooks (General, Airframe, Powerplant) and AC 43.13-1B, 7,237 chunks.\n\n",
          "## Automatic checks\n\n", md_table(summary), "\n\n",
          f"Summaries failing a check: {len(bad)} (see reports/rag_results.csv).\n\n",
          "## Faithfulness (manual)\n\nScore each summary in `reports/rag_faithfulness_sheet.csv` against its evidence:\n\n",
          RUBRIC, "\n\n## Examples\n\n", *ex]
    (rep / f"rag{suffix}.md").write_text("".join(md), encoding="utf-8")
    log.info("wrote reports/rag.md\n%s", summary.to_string())


if __name__ == "__main__":
    main()
